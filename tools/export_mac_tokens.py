"""The studio's design tokens for the Mac app: the palettes, spacing and radii of clipasso_studio/gui/theme.py and the
colour pairs tests/test_theme_contrast.py measures – written as Swift (StudioCore/Design/Tokens.generated.swift), so
the Mac app has the same colours without copying them by hand.

    python tools/export_mac_tokens.py [--out PATH]

tests/test_mac_tokens.py checks that the file is current.
"""

from __future__ import annotations

import argparse
import dataclasses
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
DEFAULT_OUT = ROOT / "macos" / "Sources" / "StudioCore" / "Design" / "Tokens.generated.swift"


def _swift_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def swift() -> str:
    from clipasso_studio.gui import theme
    from tests import test_theme_contrast as contrast

    fields = [f.name for f in dataclasses.fields(theme.Palette)]
    lines = ["// Generated by tools/export_mac_tokens.py from clipasso_studio/gui/theme.py – do not edit by hand.", "",
             "/// A palette of the studio (gui/theme.py `Palette`): colours as #RRGGBB.",
             "public struct Palette: Sendable, Hashable {"]
    lines += [f"    public let {name}: String" for name in fields]
    lines += ["}", "", "extension Palette {"]
    for const in ("DARK", "LIGHT"):
        p = getattr(theme, const)
        args = ", ".join(f"{name}: {_swift_string(getattr(p, name))}" for name in fields)
        lines.append(f"    public static let {const.lower()} = Palette({args})")
    lines += ["}", "", "/// Distances (pt) and radii of the studio's shapes (gui/theme.py).", "public enum Spacing {"]
    for name in ("SPACE_XS", "SPACE_S", "SPACE_M", "SPACE_L", "SPACE_XL", "COLUMN_PADDING", "PAGE_SPACING",
                 "HEADER_HEIGHT", "FOOTER_HEIGHT", "LEFT_COLUMN", "LEFT_COLUMN_MIN", "LEFT_COLUMN_MAX", "RIGHT_COLUMN",
                 "FILTER_COLUMN", "READING_WIDTH"):
        swift_name = "".join(w.capitalize() if i else w.lower() for i, w in enumerate(name.split("_")))
        lines.append(f"    public static let {swift_name}: Double = {getattr(theme, name)}")
    lines += ["}", "", "public enum Radius {"]
    for name in ("RADIUS_PROGRESS", "RADIUS_SEGMENT", "RADIUS_CONTROL", "RADIUS_BAR", "RADIUS_CARD", "RADIUS_LARGE",
                 "RADIUS_FLOAT"):
        swift_name = name.split("_", 1)[1].lower()
        lines.append(f"    public static let {swift_name}: Double = {getattr(theme, name)}")
    lines += ["}", "",
              "/// The colour pairs tests/test_theme_contrast.py measures: (palette, what, foreground, background, the "
              "lowest contrast allowed).", "public enum ContrastPairs {",
              "    public static let all: [(palette: String, what: String, fg: String, bg: String, "
              "minimum: Double)] = ["]
    for p in (theme.DARK, theme.LIGHT):
        for minimum, pairs in ((contrast.AA, contrast.pairs(p)), (3.0, contrast.ui_pairs(p))):
            for what, fg, bg in pairs:
                lines.append(f"        ({_swift_string(p.name)}, {_swift_string(what)}, {_swift_string(fg)}, "
                             f"{_swift_string(bg)}, {minimum}),")
    lines += ["    ]", "}", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--out", default=str(DEFAULT_OUT))
    args = parser.parse_args(argv)
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_bytes(swift().encode("utf-8"))
    print(f"tokens written to {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
