"""Write the hash-pinned requirements of the Mac app's own Python (requirements/lock-macos.txt).

Run after changing requirements/macos.txt (needs uv):  python tools/lock_macos.py
macos/scripts/build_python.sh installs them with ``pip install --require-hashes``, so every .app holds exactly the
same packages. Resolved for Apple Silicon (aarch64-apple-darwin) with the Python of build_python.sh, from any computer.
"""

from __future__ import annotations

import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REQ = ROOT / "requirements"
BUILD_PYTHON = ROOT / "macos" / "scripts" / "build_python.sh"
HEADER = ("# Generated by tools/lock_macos.py from macos.txt – do not edit.\n"
          "# macOS on Apple Silicon, Python {py}; installed by macos/scripts/build_python.sh with:\n"
          "# pip install --require-hashes -r lock-macos.txt\n")


def python_version() -> str:
    """The minor version of the Python the .app gets (PBS_PYTHON in build_python.sh)."""
    found = re.search(r'^PBS_PYTHON="(\d+\.\d+)\.\d+"', BUILD_PYTHON.read_text(encoding="utf-8"), re.M)
    if not found:
        raise SystemExit(f"no PBS_PYTHON in {BUILD_PYTHON}")
    return found.group(1)


def main() -> int:
    py = python_version()
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "lock.txt"
        subprocess.run(["uv", "pip", "compile", str(REQ / "macos.txt"), "--python-platform", "aarch64-apple-darwin",
                        "--python-version", py, "--generate-hashes", "--emit-index-url", "--no-header",
                        "-o", str(out)], check=True)
        text = out.read_text(encoding="utf-8").replace(str(REQ / "macos.txt"), "requirements/macos.txt")
    (REQ / "lock-macos.txt").write_text(HEADER.format(py=py) + text, encoding="utf-8")
    print("wrote", REQ / "lock-macos.txt")
    return 0


if __name__ == "__main__":
    sys.exit(main())
